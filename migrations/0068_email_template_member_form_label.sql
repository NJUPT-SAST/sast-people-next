-- 「成员信息表」按钮文案重新接回模板设置（member_form_label）。
--
-- 该字段历史上在结果邮件里渲染为「点击填写 {memberFormLabel}」，默认值
-- 「成员信息收集表」；后来的样式调整把按钮固定成「点击填写信息表」，字段从此失效——
-- 编辑模板时改了「表单按钮文案」，发出去的邮件不会变。
--
-- 现在按钮直接渲染 member_form_label（内置默认同步改为「点击填写信息表」）。
-- 为避免已有账号的邮件文案发生变化，把仍是旧内置默认值的行改写为新的按钮文案；
-- 管理员自己填过其它文案的行保持原样（从此真正生效）。
UPDATE "email_template_setting"
SET "member_form_label" = '点击填写信息表'
WHERE "member_form_label" = '成员信息收集表';